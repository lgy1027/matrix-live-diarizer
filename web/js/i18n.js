let currentLang = (() => {
  try {
    const saved = localStorage.getItem('matrix.lang');
    if (saved && STRINGS[saved]) return saved;
  } catch (e) { /* localStorage may be blocked */ }
  return 'zh';
})();

function t(key, ...args) {
  const table = STRINGS[currentLang] || STRINGS.en;
  let s = table[key];
  if (s === undefined) s = STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
  if (!args.length) return s;
  return s.replace(/\{(\d+)\}/g, (m, i) => {
    const v = args[+i];
    return v !== undefined ? v : m;
  });
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  scope.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  scope.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';
}

function setLang(lang) {
  if (!STRINGS[lang]) return;
  currentLang = lang;
  try { localStorage.setItem('matrix.lang', lang); } catch (e) { /* ignore */ }
  applyI18n();
  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

function updateLangSwitcherUI() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}
